EOF

# ── SukiSU specific ─────────────────────────────────────────────────────────
elif [ "$KSU_TYPE" = "suki" ]; then
  cat >> "$CF" << 'EOF'
CONFIG_KSU=y
CONFIG_KSU_SUSFS=y
CONFIG_KSU_SUSFS_SUS_MAP=y
